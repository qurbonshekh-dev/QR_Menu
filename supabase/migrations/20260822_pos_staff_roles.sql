-- Роли кассира и администратора.
--
-- Касса — четвёртое приложение персонала, и её сотрудники не помещаются в три
-- прежние роли: кассир не официант (у него нет столов и чаевых) и не менеджер
-- (ему нечего делать в учётных записях). Администратор — тот, кому можно всё:
-- он же заводит менеджеров.
--
-- Ограничение перечисляет роли явно: без него опечатка в коде тихо заведёт
-- сотрудника с несуществующей ролью, и он не попадёт ни в одно приложение.

alter table public.staff drop constraint if exists staff_role_check;

alter table public.staff
  add constraint staff_role_check
  check (role in ('waiter', 'cook', 'manager', 'cashier', 'admin'));

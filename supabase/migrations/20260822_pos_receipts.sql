-- Деньги видит и трогает только персонал. Аноним (гостевое меню) сюда
-- не ходит вовсе: чек ему показывает касса или официант.
do $$
declare
  t text;
begin
  foreach t in array array['cash_shifts', 'receipts', 'receipt_orders', 'receipt_items', 'receipt_payments']
  loop
    execute format('drop policy if exists "staff reads %1$s" on public.%1$I', t);
    execute format('drop policy if exists "staff writes %1$s" on public.%1$I', t);
    execute format(
      'create policy "staff reads %1$s" on public.%1$I for select to authenticated using (public.is_staff())', t);
    execute format(
      'create policy "staff writes %1$s" on public.%1$I for insert to authenticated with check (public.is_staff())', t);
  end loop;
end;
$$;

drop policy if exists "staff updates receipts" on public.receipts;
create policy "staff updates receipts" on public.receipts
  for update to authenticated using (public.is_staff()) with check (public.is_staff());

drop policy if exists "staff updates cash shifts" on public.cash_shifts;
create policy "staff updates cash shifts" on public.cash_shifts
  for update to authenticated using (public.is_staff()) with check (public.is_staff());

drop policy if exists "staff updates receipt payments" on public.receipt_payments;
create policy "staff updates receipt payments" on public.receipt_payments
  for update to authenticated using (public.is_staff()) with check (public.is_staff());
